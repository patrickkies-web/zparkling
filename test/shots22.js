/* screenshots of the new v22 screens: node test/shots22.js */
const { chromium } = (() => { try { return require('playwright'); } catch (e) { return require('/opt/npm-tools/node_modules/playwright'); } })();
const path = require('path');
const OUT = path.join(__dirname, 'shots');
require('fs').mkdirSync(OUT, { recursive: true });
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 400, height: 860 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error' && !/fonts\.g/.test(m.text()) && !/ERR_/.test(m.text())) errors.push('console: ' + m.text()); });
  await page.addInitScript(() => { try { localStorage.setItem('altesocke.tour', JSON.stringify({ done: 1, name: '', roll: 0 })); } catch (e) {} });
  await page.goto('file://' + path.join(__dirname, 'debug.html'));
  const ev = code => page.evaluate(c => window.__ev(c), code);
  const shot = async (name, fullPage) => { await page.waitForTimeout(350); await page.screenshot({ path: path.join(OUT, name + '.png'), fullPage: !!fullPage }); };
  const bodyShot = async (name) => { await page.waitForTimeout(400); const el = await page.$('.body'); const h = await page.evaluate(() => { const b = document.querySelector('.body'); return b ? b.scrollHeight : 860; }); await page.setViewportSize({ width: 400, height: Math.min(2600, h + 200) }); await page.waitForTimeout(250); await page.screenshot({ path: path.join(OUT, name + '.png') }); await page.setViewportSize({ width: 400, height: 860 }); };
  await ev("A.loadDemo(); A.matPreset({v:'all'}); A.openRun(); A.startRun();");
  const force = (game, fmt) => ev("var r=R(); r.pending = makeGameStep(r.who[0], {focus: " + (fmt === 'duellGast' || fmt === 'solo' ? '[r.who[0]]' : 'r.who.slice()') + ", together:'gemeinsam', variant:'socke', themes: themesOf(r.who)}, '" + game + "', '" + fmt + "'); r.pending.track = r.tracks[0].id; r.pending.unitNo = r.tracks[0].pos + 1; r.steps = Math.max(r.steps, 1); commit(); go('step');");
  /* the challenge */
  await force('zwiebel', 'duellGast');
  await bodyShot('01-pick');
  await page.click('[data-act="chWheel"]');
  await page.waitForTimeout(1200); await shot('02-wheel-spin');
  await page.waitForTimeout(1800); await bodyShot('03-wheel-done');
  await page.click('[data-act="chGo"]');
  await page.waitForTimeout(700); await bodyShot('04-vs');
  await page.click('[data-act="chStake"][data-i="1"]');
  await page.click('[data-act="chPlay"]');
  await bodyShot('05-play');
  await page.click('[data-act="stepResolve"][data-v="fail"]');
  await bodyShot('06-result-revanche');
  await page.click('[data-act="chRevanche"]');
  await bodyShot('07-revanche-play');
  await page.click('[data-act="stepResolve"][data-v="ok"]');
  await bodyShot('08-result-stake');
  await page.click('[data-act="stepContinue"]');
  /* the station */
  await ev("var r=R(); r.pending = prepHcStep(r, { kind: 'handicap', track: r.tracks[0].id, main: r.who[0] }); commit(); go('step');");
  await bodyShot('10-hc-pick');
  await page.click('.pk >> nth=1');
  await page.click('[data-act="hcNext"]');
  await bodyShot('11-hc-choose');
  await page.click('[data-act="hcChoose"] >> nth=0');
  await page.click('[data-act="hcPicked"]');
  await bodyShot('12-hc-done');
  await page.click('[data-act="stepResolve"][data-v="handicap"]');
  await bodyShot('13-run-with-hc');
  /* specials */
  await force('daumenblitz', 'duell');
  await bodyShot('20-blitz');
  await page.click('[data-act="bzStart"]');
  await page.waitForTimeout(150); await shot('21-blitz-wait');
  await page.waitForTimeout(4200); await shot('22-blitz-go');
  await page.locator('[data-bz="0"]').dispatchEvent('pointerdown');
  await bodyShot('23-blitz-after');
  await force('loeffelreflex', 'duell');
  await page.click('[data-act="lrStart"]');
  await page.waitForTimeout(1600); await shot('24-loeffel-call');
  await force('gedankenleser', 'solo');
  await bodyShot('25-gedanken-pick');
  await page.click('.pk >> nth=0'); await page.click('[data-act="glGo"]');
  await bodyShot('26-gedanken-a');
  await page.click('[data-act="glA"][data-i="2"]'); await shot('27-gedanken-pass');
  await page.click('[data-act="glPass"]'); await page.click('[data-act="glB"][data-i="2"]');
  await bodyShot('28-gedanken-reveal');
  await force('ketchup', 'duell');
  await bodyShot('29-ketchup-setup');
  await page.click('[data-act="kcReady"]'); await page.click('[data-act="kcGo"]');
  await page.click('[data-act="kcHit"]'); await page.click('[data-act="kcHit"]');
  await bodyShot('30-ketchup-play');
  await force('lippenlesen', 'solo');
  await bodyShot('31-lippen');
  await page.click('[data-act="lipShow"]');
  await bodyShot('32-lippen-open');
  /* the end: duel credits */
  await ev("var r=R(); r.duel = { tom: { name: 'Tom', n: 3, gw: 2, fw: 1 }, lea: { name: 'Lea', n: 4, gw: 1, fw: 3 } }; r.pending = null; r.finished = true; commit(); go('finish');");
  await bodyShot('40-finish');
  console.log(errors.length ? errors.join('\n') : 'NO PAGE ERRORS');
  await browser.close();
})();
